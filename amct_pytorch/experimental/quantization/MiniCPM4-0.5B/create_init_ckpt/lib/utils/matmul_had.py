# ---------------------------------------------------------------------------
# Hadamard matrix cache — auto-generate on first import if missing
# ---------------------------------------------------------------------------
# The cache is a safetensors file keyed by matrix dimension (int).  On cold
# start (missing file) we generate all matrices and write them out so
# subsequent imports are instant.
#
# For 2-power dimensions: Sylvester construction.
# For dimensions n = q+1 where q ≡ 3 (mod 4) is a prime power: Paley Type I.
#    (GF(q) arithmetic is implemented for prime fields and GF(3^k) up to k=5.)
# The remaining dimensions are decomposed as Kronecker products of smaller
# known Hadamard matrices.
# ---------------------------------------------------------------------------


def _hadamard_sylvester(n):
    """Sylvester construction: n must be a power of 2."""
    assert (n & (n - 1) == 0) and n > 0
    H = torch.ones(1, 1, dtype=torch.float32)
    while H.shape[0] != n:
        H = torch.cat((torch.cat([H, H], 1), torch.cat([H, -H], 1)), 0)
    return H


def _is_prime_power(q):
    """Return (is_prime_power, prime, exponent) for q."""
    if q < 2:
        return False, 0, 0
    for p in range(2, math.isqrt(q) + 1):
        if q % p == 0:
            k = 0
            while q % p == 0:
                q //= p
                k += 1
            return q == 1, p, k
    return True, q, 1


# ---------------------------------------------------------------------------
# GF(p^k) arithmetic for Paley Type I construction
# ---------------------------------------------------------------------------
# Elements are represented as integers in [0, p^k-1] with the polynomial
# encoding: value = sum(coeff_i * p^i) where coeff_i is the coefficient of t^i.
# Multiplication uses a primitive polynomial for reduction.

_GF3_POLYS = {
    # (p, k) -> (poly_coeffs, generator)
    # poly: t^k = sum(poly[i] * t^i)  (mod p)
    # For p=3^k (k=3,5): standard primitive polynomials
    (3, 3): ([2, 1, 0], 3),   # t^3 = 2 + t  (GF(27))
    (3, 5): ([2, 1, 0, 0, 0], 3),  # t^5 = 2 + t  (GF(243))
}


def _gf_mult(a, b, p, k, poly):
    """Multiply two elements in GF(p^k)."""
    # Convert to polynomial coefficients
    ca = [(a // (p ** i)) % p for i in range(k)]
    cb = [(b // (p ** i)) % p for i in range(k)]
    # Multiply polynomials
    coeffs = [0] * (2 * k)
    for i in range(k):
        for j in range(k):
            coeffs[i + j] = (coeffs[i + j] + ca[i] * cb[j]) % p
    # Reduce using t^k = sum(poly[i] * t^i)
    for i in range(2 * k - 1, k - 1, -1):
        if coeffs[i] != 0:
            factor = coeffs[i]
            for j in range(k):
                coeffs[i - k + j] = (coeffs[i - k + j] + factor * poly[j]) % p
            coeffs[i] = 0
    return sum(coeffs[i] * (p ** i) for i in range(k))


def _gf_sub(a, b, p, k):
    """Subtract two elements in GF(p^k)."""
    ca = [(a // (p ** i)) % p for i in range(k)]
    cb = [(b // (p ** i)) % p for i in range(k)]
    result = [(ca[i] - cb[i]) % p for i in range(k)]
    return sum(result[i] * (p ** i) for i in range(k))


def _make_gf_legendre(p, k):
    """Build a Legendre symbol lookup table for GF(p^k).

    Returns a list legendre[x] for x in [0, p^k-1].
    """
    q = p ** k
    poly, gen = _GF3_POLYS[(p, k)]
    # Build log table via generator
    log_table = {0: -1}
    current = 1
    for i in range(q - 1):
        log_table[current] = i
        current = _gf_mult(current, gen, p, k, poly)
    # Build Legendre table
    legendre = [0] * q
    for x in range(1, q):
        legendre[x] = 1 if log_table[x] % 2 == 0 else -1
    return legendre, poly


def _paley_type1_prime(p):
    """Paley Type I construction: p must be prime, p ≡ 3 (mod 4)."""
    def chi(x):
        if x == 0:
            return 0
        return 1 if pow(x, (p - 1) // 2, p) == 1 else -1

    Q = torch.zeros(p, p, dtype=torch.float32)
    for i in range(p):
        for j in range(p):
            if i != j:
                Q[i, j] = chi((i - j) % p)

    n = p + 1
    H = torch.zeros(n, n, dtype=torch.float32)
    H[0, 0] = 1
    H[0, 1:] = 1
    H[1:, 0] = 1
    H[1:, 1:] = Q - torch.eye(p, dtype=torch.float32)
    return H


def _paley_type1_prime_power(p, k):
    """Paley Type I construction over GF(p^k)."""
    q = p ** k
    legendre, _ = _make_gf_legendre(p, k)

    Q = torch.zeros(q, q, dtype=torch.float32)
    for i in range(q):
        for j in range(q):
            if i != j:
                diff = _gf_sub(i, j, p, k)
                Q[i, j] = legendre[diff]

    n = q + 1
    H = torch.zeros(n, n, dtype=torch.float32)
    H[0, 0] = 1
    H[0, 1:] = 1
    H[1:, 0] = 1
    H[1:, 1:] = Q - torch.eye(q, dtype=torch.float32)
    return H


