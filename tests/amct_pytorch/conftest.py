import os
import sys
from unittest.mock import MagicMock

# Add project root to path so amct_pytorch is importable without installation
_project_root = os.path.join(os.path.dirname(__file__), "..", "..")
sys.path.insert(0, os.path.abspath(_project_root))

# Mock graph_based_compression to avoid requiring compiled proto files.
# The calibration modules under test (minmax, smoothquant, etc.) do not
# depend on graph_based_compression; it is only pulled in by amct_pytorch/__init__.py.
_mock = MagicMock()
_mock.__all__ = []
sys.modules.setdefault("amct_pytorch.graph_based_compression", _mock)
sys.modules.setdefault("amct_pytorch.graph_based_compression.amct_pytorch", _mock)

# Mock transformers.cache_utils.DynamicCache: pulled in by the deepseekv3 and
# longcat attention modules that get imported through amct_pytorch.algorithm,
# but unused by the calibration modules under test.
_transformers_mock = MagicMock()
_transformers_cache_utils_mock = MagicMock()
sys.modules.setdefault("transformers", _transformers_mock)
sys.modules.setdefault("transformers.cache_utils", _transformers_cache_utils_mock)

# Mock compiled protobuf modules under amct_pytorch.classic.graph_based.amct_pytorch.proto.
# These are generated by build.sh (protoc) and are not present in the source tree.
# The configuration/check module chain pulls them in at import time.
# We must NOT mock the proto package itself (its real __init__.py must be skipped by
# mocking the pb2 submodules before they are imported, then the __init__.py relative
# imports will resolve from sys.modules).
_proto_base = "amct_pytorch.classic.graph_based.amct_pytorch.proto"
for _pb2 in [
    "calibration_config_pytorch_pb2",
    "retrain_config_pytorch_pb2",
    "distill_config_pytorch_pb2",
    "scale_offset_record_pytorch_pb2",
    "quant_calibration_config_pytorch_pb2",
    "basic_info_pb2",
]:
    _m = MagicMock()
    _m.__spec__ = MagicMock()
    sys.modules.setdefault(f"{_proto_base}.{_pb2}", _m)

# Mock compiled protobuf modules under amct_pytorch.classic.graph_based.proto.
# retrain_proto.py imports from ...proto (i.e. amct_pytorch.classic.graph_based.proto)
# which is also a build-time generated package not present in the source tree.
_gb_proto_base = "amct_pytorch.classic.graph_based.proto"
_gb_proto_pkg = MagicMock()
_gb_proto_pkg.__spec__ = MagicMock()
sys.modules.setdefault(_gb_proto_base, _gb_proto_pkg)
for _pb2 in [
    "retrain_config_pb2",
]:
    _m2 = MagicMock()
    _m2.__spec__ = MagicMock()
    sys.modules.setdefault(f"{_gb_proto_base}.{_pb2}", _m2)

# Mock amct_pytorch.classic.graph_based.utils (build-time package, not in source tree).
# retrain_proto.py imports from ...utils.log for LOGGER.
_gb_utils_base = "amct_pytorch.classic.graph_based.utils"
_gb_utils_pkg = MagicMock()
_gb_utils_pkg.__spec__ = MagicMock()
sys.modules.setdefault(_gb_utils_base, _gb_utils_pkg)
for _util_mod in ["log"]:
    _m3 = MagicMock()
    _m3.__spec__ = MagicMock()
    sys.modules.setdefault(f"{_gb_utils_base}.{_util_mod}", _m3)
